import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

// Run against Vite; requests are intercepted so this never modifies campaign data.
const browser = await chromium.launch({ headless: true, channel: process.env.MAP_TEST_BROWSER ?? (process.platform === 'win32' ? 'msedge' : undefined) });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let role = 'GAMEMASTER';
const campaign = () => ({ id: 'demo', handle: 'demo', name: 'Discovery', role, isMember: true });
const asset = id => ({ id, width: 1400, height: 700, displayName: 'The Shattered Kingdoms', imageCredit: null });
const layers = [{ id: 'places', name: 'Places', defaultEnabled: true, sortOrder: 0, color: '#5a8' }];
let objects = [{ id: 'region', kind: 'region', label: 'Mira’s haven', layerId: 'places', groupId: null, geometry: { type: 'Polygon', coordinates: [[[.4,.4],[.6,.4],[.6,.6],[.4,.6],[.4,.4]]] }, style: {}, x: 700, y: 350, revelation: 'REVEALED', visibility: 'PUBLIC' }];
const scenes = [];
const writes = [];
let failNextSave = false;
await page.route('**/api/**', async route => {
  const request = route.request();
  const url = new URL(request.url());
  const path = url.pathname;
  let body = {};
  if (path.includes('/events')) return route.fulfill({ status: 200, contentType: 'text/event-stream', body: ': fixture\n\n' });
  if (path.startsWith('/api/assets/')) return route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="1400" height="700"><rect width="1400" height="700" fill="#315966"/><path d="M0 100L400 0 600 250 500 600 0 700Z" fill="#9cac68"/><path d="M850 50L1400 100 1400 700 800 550 1000 300Z" fill="#d4bf83"/></svg>' });
  if (path.endsWith('/auth/me')) body = { user: { id: 'author', email: 'author@example.test', role: 'USER' } };
  else if (path.endsWith('/wiki/tree')) body = { campaign: campaign(), tree: [], players: [] };
  else if (path.endsWith('/wiki/pins')) body = { shortcuts: [] };
  else if (path.endsWith('/time-tracking')) return route.fulfill({ status: 404, json: { error: 'No calendar' } });
  else if (path.endsWith('/scene')) {
    scenes.push(url);
    const ids = url.searchParams.has('layerIds') ? url.searchParams.get('layerIds').split(',') : ['places'];
    body = { scene: { layers: path.includes('/second/') ? [{ ...layers[0], id: 'second-default' }] : layers, groups: [], objects: objects.filter(o => !o.layerId || ids.includes(o.layerId)), presentationPresets: [], hiddenZoneGeometries: [] } };
  } else if (path.endsWith('/objects') && request.method() === 'POST') {
    const input = request.postDataJSON(); writes.push(input);
    const object = { ...input, id: `created-${writes.length}`, x: 0, y: 0 };
    objects.push(object); body = { object };
  } else if (path.includes('/objects/') && request.method() === 'PATCH') {
    if (failNextSave) { failNextSave = false; return route.fulfill({ status: 500, json: { error: 'Fixture save failure' } }); }
    const input = request.postDataJSON(); objects = objects.map(o => o.id === path.split('/').at(-1) ? { ...o, ...input } : o); body = { object: objects[0] };
  } else if (path.endsWith('/maps')) body = { maps: [asset('first'), asset('second')] };
  else if (/\/maps\/(first|second)$/.test(path)) body = { map: asset(path.split('/').at(-1)), linkedWikiPages: [] };
  else if (path === '/api/campaigns/demo') body = { campaign: campaign() };
  await route.fulfill({ json: body });
});
try {
  await page.goto(`${process.env.MAP_TEST_URL ?? 'http://localhost:5173'}/tests/map-workspace/index.html`);
  await page.getByRole('button', { name: 'View map fullscreen' }).click();
  const fullscreen = page.getByRole('dialog', { name: 'Fullscreen map viewer' });
  await fullscreen.waitFor();
  assert.equal(await page.locator('#map-legend').isVisible(), false);
  await page.locator('.leaflet-container').evaluate(el => { el.dataset.instance = 'preserved'; });
  await page.getByRole('button', { name: 'Edit map', exact: true }).click();
  assert.equal(await page.locator('#map-legend').isVisible(), false);
  await page.getByRole('button', { name: 'Area', exact: true }).click();
  await page.mouse.click(700, 420);
  await page.waitForTimeout(350);
  await page.mouse.click(800, 420);
  assert.equal(await fullscreen.getAttribute('data-draw-vertices'), '2');
  await page.getByRole('button', { name: 'Exit fullscreen map' }).click();
  assert.equal(await page.locator('.leaflet-container').getAttribute('data-instance'), 'preserved');
  assert.equal(await page.getByRole('button', { name: 'Area', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'View map fullscreen' }).click();
  assert.equal(await fullscreen.getAttribute('data-draw-vertices'), '2');
  await page.keyboard.press('Escape');
  assert.equal(await fullscreen.count(), 1);
  assert.equal(await page.getByRole('button', { name: 'Select / Pan' }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Circle', exact: true }).click();
  await page.mouse.click(750, 450);
  await page.waitForTimeout(350);
  await page.mouse.click(850, 450);
  await page.waitForFunction(() => document.querySelector('[aria-label="Select / Pan"]')?.getAttribute('aria-pressed') === 'true');
  assert.equal(writes.length, 1);
  assert.equal(writes[0].kind, 'region');
  assert.equal(writes[0].geometry.coordinates[0].length, 65);
  await page.getByRole('button', { name: 'Path', exact: true }).click();
  await page.mouse.click(750, 450);
  await page.waitForTimeout(350);
  await page.mouse.click(850, 450);
  await page.getByRole('button', { name: 'Finish', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Select / Pan"]')?.getAttribute('aria-pressed') === 'true');
  assert.equal(writes[1].kind, 'path');
  await page.getByRole('button', { name: 'Text', exact: true }).click();
  page.once('dialog', dialog => dialog.accept('Aster’s landing'));
  await page.mouse.click(800, 400);
  await page.waitForFunction(() => document.querySelector('[aria-label="Select / Pan"]')?.getAttribute('aria-pressed') === 'true');
  assert.equal(writes[2].kind, 'label');
  await page.getByRole('button', { name: 'Pin', exact: true }).click();
  await page.mouse.click(700, 350);
  await page.getByRole('dialog', { name: 'Add map pin' }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'Add map pin' }).count(), 0);
  assert.equal(await fullscreen.count(), 1);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Layers & Legend', exact: true }).click();
  await page.getByRole('button', { name: 'Mira’s haven', exact: true }).click();
  const properties = page.locator('.map-properties-floating');
  await properties.waitFor();
  await properties.getByRole('textbox', { name: 'Label', exact: true }).fill('Unsaved name');
  failNextSave = true;
  await properties.getByRole('button', { name: 'Save', exact: true }).click();
  await properties.getByText('Fixture save failure', { exact: true }).waitFor();
  assert.equal(await properties.getByRole('textbox', { name: 'Label', exact: true }).inputValue(), 'Unsaved name');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Done editing' }).click();
  assert.equal(await properties.isVisible(), true);
  await page.getByRole('button', { name: 'Exit fullscreen map' }).click();
  await page.getByRole('button', { name: 'View map fullscreen' }).click();
  assert.equal(await properties.getByRole('textbox', { name: 'Label', exact: true }).inputValue(), 'Unsaved name');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Done editing' }).click();
  assert.equal(await properties.count(), 0);
  assert.ok(await page.locator('.leaflet-overlay-pane .leaflet-interactive').count() > 0);
  await page.getByRole('button', { name: 'Places', exact: true }).click();
  await page.waitForTimeout(200);
  assert.equal(scenes.at(-1).searchParams.get('layerIds'), '');
  await fullscreen.focus();
  for (let i = 0; i < 20; i++) {
    await page.keyboard.press(i % 2 ? 'Shift+Tab' : 'Tab');
    assert.equal(await fullscreen.evaluate(el => el.contains(document.activeElement)), true);
  }
  await mkdir('artifacts/map-workspace', { recursive: true });
  await page.screenshot({ path: 'artifacts/map-workspace/desktop.png' });
  for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport);
    await page.getByRole('button', { name: 'Edit map', exact: true }).click();
    const dock = await page.locator('.map-fullscreen-dock').boundingBox();
    const zoom = await page.locator('.leaflet-control-zoom').boundingBox();
    assert.ok(dock.x >= 0 && dock.x + dock.width <= viewport.width);
    assert.ok(dock.y >= 0 && dock.y + dock.height <= viewport.height);
    assert.ok(dock.x >= zoom.x + zoom.width || dock.y + dock.height <= zoom.y);
    await page.screenshot({ path: `artifacts/map-workspace/${viewport.width}.png` });
    await page.getByRole('button', { name: 'Done editing' }).click();
  }
  await page.getByRole('button', { name: 'Exit fullscreen map' }).click();
  await page.getByRole('link', { name: 'Second map' }).click();
  await page.getByRole('button', { name: 'View map fullscreen' }).waitFor();
  await page.waitForTimeout(200);
  assert.ok(scenes.filter(url => url.pathname.includes('/second/')).every(url => !url.searchParams.has('layerIds')));
  role = 'PLAYER';
  await page.getByRole('button', { name: 'Edit map', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh permissions' }).click();
  await page.getByRole('button', { name: 'View map fullscreen' }).click();
  await page.waitForTimeout(250);
  assert.equal(await page.getByRole('toolbar', { name: 'Map editing tools' }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Map workspace browser checks passed. Screenshots: artifacts/map-workspace/');
} catch (error) {
  await mkdir('artifacts/map-workspace', { recursive: true });
  await page.screenshot({ path: 'artifacts/map-workspace/failure.png' });
  console.error({ errors, writes, text: (await page.locator('body').innerText()).slice(-1800) });
  throw error;
} finally { await browser.close(); }
